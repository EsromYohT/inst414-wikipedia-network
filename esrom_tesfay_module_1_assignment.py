import requests
import time
import random


# Wikipedia's free API address
url = "https://en.wikipedia.org/w/api.php"
headers = {"User-Agent": "INST414-class-project (etesfay2@terpmail.umd.edu)"}

# This function gets the list of links on one Wikipedia page
def get_links(title):
    params = {
        "action": "query",
        "titles": title,
        "prop": "links",
        "pllimit": "max",
        "plnamespace": 0,
        "format": "json",
    }
    response = requests.get(url, params=params, headers=headers)
    data = response.json()
    link_list = []
    for page in data["query"]["pages"].values():
        for link in page.get("links", []):
            link_list.append(link["title"])
    return link_list

# Our starting article
seed = "Machine learning"

random.seed(42)
all_links = get_links(seed)
nodes = [seed] + random.sample(all_links, 99)

# For each article, find which of the other 100 it links to
edges = []
for article in nodes:
    for target in get_links(article):
        if target in nodes and target != article:
            edges.append((article, target))
    time.sleep(0.1)

print("Done! Number of edges:", len(edges))

import networkx as nx
import pandas as pd

G = nx.DiGraph()
G.add_edges_from(edges)

# Importance measure 1: in-degree = how many articles link TO this one
in_degree = dict(G.in_degree())

# Importance measure 2: PageRank = links from important articles count more
pagerank = nx.pagerank(G)

# Put them in a table, sorted by PageRank
table = pd.DataFrame({"in_degree": in_degree, "pagerank": pagerank})
table = table.sort_values("pagerank", ascending=False)
top10 = table.head(10)

print("Nodes:", G.number_of_nodes())
print("Edges:", G.number_of_edges())
print(top10)

remove = [name for name in G.nodes if "(identifier)" in name]
print("Removing:", remove)
G.remove_nodes_from(remove)

in_degree = dict(G.in_degree())
pagerank = nx.pagerank(G)
table = pd.DataFrame({"in_degree": in_degree, "pagerank": pagerank})
table = table.sort_values("pagerank", ascending=False)
top10 = table.head(10)

print("Nodes:", G.number_of_nodes())
print("Edges:", G.number_of_edges())
print(top10)

print("Self-loops (should be 0):", nx.number_of_selfloops(G))
print("Duplicate edges (should be 0):", len(edges) - len(set(edges)))

# Do the two importance measures roughly agree?
top_by_pagerank = set(top10.index)
top_by_indegree = set(table.sort_values("in_degree", ascending=False).head(10).index)
print("Overlap between top 10 lists:", len(top_by_pagerank & top_by_indegree), "out of 10")

